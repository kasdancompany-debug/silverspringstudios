/**
 * One-shot production wiring helper.
 *
 * Usage (after you create Supabase + Resend accounts):
 *   node scripts/wire-production.mjs
 *
 * Reads secrets from environment (or prompts via stdin) and:
 *  1. Pushes them to Vercel (production + preview + development)
 *  2. Writes a local .env.local for migration / admin setup
 *
 * Does NOT print secrets back to the console.
 */
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");
const readline = require("node:readline");

const ROOT = path.resolve(__dirname, "..");

const KEYS = [
  {
    name: "NEXT_PUBLIC_SUPABASE_URL",
    hint: "Project Settings → API → Project URL (https://xxxx.supabase.co)",
  },
  {
    name: "NEXT_PUBLIC_SUPABASE_ANON_KEY",
    hint: "Project Settings → API → anon public key",
  },
  {
    name: "SUPABASE_SERVICE_ROLE_KEY",
    hint: "Project Settings → API → service_role key (secret)",
  },
  {
    name: "RESEND_API_KEY",
    hint: "https://resend.com/api-keys → Create API key",
  },
  {
    name: "EMAIL_FROM",
    hint: 'Use: Silver Spring Studios <onboarding@resend.dev> until a domain is verified',
    defaultValue: "Silver Spring Studios <onboarding@resend.dev>",
  },
];

const FIXED = {
  NEXT_PUBLIC_SITE_URL: "https://silverspringstudios.vercel.app",
  NEXT_PUBLIC_CONTACT_EMAIL: "silverspringfilms@gmail.com",
  ADMIN_NOTIFICATION_EMAIL: "silverspringfilms@gmail.com",
  NEXT_PUBLIC_DEMO_MODE: "false",
};

function ask(rl, question, fallback) {
  return new Promise((resolve) => {
    const suffix = fallback ? ` [${fallback}]` : "";
    rl.question(`${question}${suffix}: `, (answer) => {
      const trimmed = answer.trim();
      resolve(trimmed || fallback || "");
    });
  });
}

function vercelEnvAdd(name, value, environment) {
  const result = spawnSync(
    "npx",
    ["vercel", "env", "add", name, environment, "--force"],
    {
      cwd: ROOT,
      input: value,
      encoding: "utf8",
      shell: true,
    },
  );
  if (result.status !== 0) {
    console.error(result.stderr || result.stdout);
    throw new Error(`Failed to set ${name} for ${environment}`);
  }
  console.log(`  ✓ ${name} → ${environment}`);
}

async function main() {
  console.log("\nSilver Spring Studios — wire production secrets\n");
  console.log("Paste values from Supabase + Resend. Nothing is echoed back.\n");

  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const secrets = { ...FIXED };

  for (const key of KEYS) {
    console.log(`\n${key.name}`);
    console.log(`  ${key.hint}`);
    const value = await ask(rl, "  value", key.defaultValue);
    if (!value) {
      rl.close();
      throw new Error(`Missing ${key.name}`);
    }
    secrets[key.name] = value;
  }
  rl.close();

  const envs = ["production", "preview", "development"];
  console.log("\nPushing to Vercel…");
  for (const [name, value] of Object.entries(secrets)) {
    for (const environment of envs) {
      vercelEnvAdd(name, value, environment);
    }
  }

  const localLines = [
    "# Generated by scripts/wire-production.mjs — do not commit",
    ...Object.entries(secrets).map(([k, v]) => `${k}=${v}`),
    "",
  ];
  fs.writeFileSync(path.join(ROOT, ".env.local"), localLines.join("\n"), "utf8");
  console.log("\n✓ Wrote .env.local");
  console.log("\nNext:");
  console.log("  1. In Supabase SQL editor, run migrations 001 → 005 in order");
  console.log("  2. Create private Storage bucket: submission-files");
  console.log("  3. Create Auth user, then upsert profiles.role = 'admin'");
  console.log("  4. npx vercel --prod   (or push to master to redeploy)");
  console.log("");
}

main().catch((error) => {
  console.error("\nFailed:", error.message);
  process.exit(1);
});
